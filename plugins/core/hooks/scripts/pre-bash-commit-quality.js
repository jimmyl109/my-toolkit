#!/usr/bin/env node
/**
 * PreToolUse Hook: Commit Quality (id: commit-quality)
 *
 * Runs on `git commit` Bash commands and inspects the files being committed.
 *   BLOCKS (exit 2): likely secrets (API keys/tokens, private keys) and staged .env files.
 *   WARNS (context shown to Claude, commit proceeds): console.log, debugger, TODO/FIXME
 *   without an issue reference, ESLint errors, and a poorly formed commit message.
 *
 * Disable with MY_TOOLKIT_DISABLED_HOOKS=commit-quality (turns off both the block and the warnings).
 *
 * A PreToolUse hook runs BEFORE the command, so for `git add X && git commit` nothing is staged yet:
 * the hook therefore also scans the files a chained `git add` will stage and the command text itself.
 * (A file whose content is generated by the same command, e.g. `echo $KEY > f && git add f && git commit`,
 * is only caught if the secret appears literally in the command.)
 *
 * Adapted from ECC scripts/hooks/pre-bash-commit-quality.js: secrets now block while everything
 * else warns through a channel Claude can see (ECC wrote to stderr, which exit-0 hooks discard);
 * pylint/golint support removed; the commit message check looks at the first line only and
 * understands HEREDOC messages; `git commit -a` is handled; staged files of any type are scanned
 * for secrets.
 */

'use strict';

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');
const { runHook } = require('./lib/hook-io');

const MAX_FILE_BYTES = 1024 * 1024;
const JS_TS = /\.(js|jsx|ts|tsx|mjs|cjs)$/;
const LOCKFILES = /(^|\/)(package-lock\.json|yarn\.lock|pnpm-lock\.yaml|bun\.lockb?|composer\.lock|Cargo\.lock|poetry\.lock)$/;
const ENV_FILE = /(^|\/)\.env(\.[^/]+)?$/;
const ENV_TEMPLATE = /\.(example|sample|template|dist)$/i;

function git(cwd, args) {
  const result = spawnSync('git', args, { cwd, encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 });
  return result.status === 0 ? result.stdout : null;
}

/**
 * Obvious non-secret placeholders (env references, interpolations, <TOKENS>, REPLACE_ME ...).
 * Deliberately narrow: arbitrary high-entropy values must still be flagged.
 */
function isPlaceholderSecret(value) {
  const v = (value || '').trim();
  if (v.length === 0) return true;
  if (/^process\.env\.[A-Za-z0-9_]+$/.test(v)) return true;
  if (/^\$\{[^}]*\}$/.test(v)) return true;
  if (/^<[^<>]*>$/.test(v)) return true;
  if (/^(REPLACE_ME|CHANGE_?ME|YOUR[_-]?API[_-]?KEY|YOUR[_-]?KEY[_-]?HERE|API[_-]?KEY|SECRET|TOKEN|KEY|TODO|TBD|FIXME|XXX+)$/i.test(v)) return true;
  return false;
}

const SECRET_PATTERNS = [
  { pattern: /sk-ant-[a-zA-Z0-9_-]{20,}/, name: 'Anthropic API key' },
  { pattern: /sk-[a-zA-Z0-9]{20,}/, name: 'OpenAI-style API key' },
  { pattern: /gh[pousr]_[a-zA-Z0-9]{36,}/, name: 'GitHub token' },
  { pattern: /AKIA[A-Z0-9]{16}/, name: 'AWS access key' },
  { pattern: /-----BEGIN (?:[A-Z]+ )?PRIVATE KEY(?: BLOCK)?-----/, name: 'private key' },
  { pattern: /api[_-]?key\s*[=:]\s*['"]([^'"]+)['"]/i, name: 'API key', valueGroup: 1 },
  { pattern: /api[_-]?key\s*[=:]\s*(?!['"])((?=[A-Za-z0-9_-]*\d)[A-Za-z0-9_-]{12,})/i, name: 'API key', valueGroup: 1 }
];

function findSecrets(content) {
  const found = [];
  content.split('\n').forEach((line, index) => {
    for (const { pattern, name, valueGroup } of SECRET_PATTERNS) {
      const match = line.match(pattern);
      if (match && !(valueGroup && isPlaceholderSecret(match[valueGroup]))) {
        found.push(`${name} at line ${index + 1}`);
        break;
      }
    }
  });
  return found;
}

function findCodeIssues(content) {
  const warnings = [];
  content.split('\n').forEach((line, index) => {
    const trimmed = line.trim();
    const n = index + 1;
    const todo = line.match(/(?:\/\/|#)\s*(TODO|FIXME):?\s*(\S.*)/);
    if (todo && !/#\d+|issue/i.test(todo[2])) warnings.push(`${todo[1]} without issue reference at line ${n}`);
    if (trimmed.startsWith('//') || trimmed.startsWith('*') || trimmed.startsWith('#')) return;
    if (line.includes('console.log')) warnings.push(`console.log at line ${n}`);
    if (/\bdebugger\b/.test(line)) warnings.push(`debugger statement at line ${n}`);
  });
  return warnings;
}

function commitMessageFirstLine(command) {
  const heredoc = command.match(/<<-?\s*['"]?(\w+)['"]?\s*\n([^\n]*)/);
  if (heredoc) return heredoc[2].trim();
  const m = command.match(/(?:-m|--message)[=\s]+(?:"((?:\\.|[^"\\])*)"|'((?:\\.|[^'\\])*)'|([^"'\s]+))/);
  if (!m) return null;
  const text = m[1] ?? m[2] ?? m[3];
  if (text.startsWith('$(')) return null; // unknown dynamic message
  return text.split('\n')[0].trim();
}

function validateCommitMessage(command) {
  const subject = commitMessageFirstLine(command);
  if (subject === null) return [];
  const problems = [];
  const conventional = /^(feat|fix|docs|style|refactor|test|chore|build|ci|perf|revert)(\(.+\))?!?:\s*\S/;
  if (!conventional.test(subject)) problems.push('commit message is not in "type(scope): description" form (feat, fix, docs, refactor, test, chore, ...)');
  if (subject.length > 72) problems.push(`commit subject is ${subject.length} chars (keep it under 72)`);
  if (conventional.test(subject) && /^[A-Z]/.test(subject.split(':').slice(1).join(':').trim())) problems.push('subject should start lowercase after the type');
  if (subject.endsWith('.')) problems.push('commit subject should not end with a period');
  return problems;
}

function runEslint(cwd, files) {
  const bin = path.join(cwd, 'node_modules', '.bin', 'eslint');
  if (!files.length || !fs.existsSync(bin)) return null;
  const result = spawnSync(bin, files, { cwd, encoding: 'utf8', timeout: 60000 });
  if (result.status !== 1) return null; // 0 = clean, 2/null = tool problem: not our concern
  return (result.stdout + result.stderr).split('\n').filter(Boolean).slice(0, 20).join('\n');
}

/**
 * Files a `git add ...` chained in the SAME Bash command is about to stage (nothing is staged yet when
 * this PreToolUse hook runs). Returns null when the command has no `git add`; otherwise a list of paths.
 */
function chainedAddPaths(command, cwd) {
  const m = command.match(/\bgit(?:\s+-\S+(?:\s+\S+)?)*?\s+add\b([^;&|\n]*)/);
  if (!m) return null;
  const args = m[1].trim().split(/\s+/).filter(Boolean);
  const everything = args.some(a => /^(-A|--all|-u|--update|\.|\*)$/.test(a));
  const explicit = args.filter(a => !a.startsWith('-'));
  const changed = () => [
    ...(git(cwd, ['diff', '--name-only', '--diff-filter=ACMR', 'HEAD']) || '').split('\n'),
    ...(git(cwd, ['ls-files', '--others', '--exclude-standard']) || '').split('\n')
  ].filter(Boolean);
  if (everything) return changed();
  const paths = [];
  for (const arg of explicit) {
    let stat;
    try { stat = fs.statSync(path.join(cwd, arg)); } catch { continue; }
    if (stat.isDirectory()) return changed();
    paths.push(arg);
  }
  return paths;
}

runHook('commit-quality', ({ input, block, context }) => {
  const command = String(input.tool_input?.command || '');
  if (!/\bgit(?:\s+-[Cc]\s+\S+|\s+--[\w-]+(?:=\S+)?)*\s+commit\b/.test(command)) return;

  const cwd = input.cwd || process.cwd();
  const stageAll = /\s(?:-[a-zA-Z]*a[a-zA-Z]*|--all)(\s|$)/.test(command.split(/\s-m\b|\s--message\b/)[0]);
  const listing = stageAll
    ? git(cwd, ['diff', '--name-only', '--diff-filter=ACMR', 'HEAD'])
    : git(cwd, ['diff', '--cached', '--name-only', '--diff-filter=ACMR']);
  const staged = (listing || '').split('\n').filter(Boolean);
  const chained = chainedAddPaths(command, cwd) || [];

  const blockers = [];
  const warnings = [];
  const lintable = [];

  // Secrets typed into the command itself (e.g. a file created and committed in one Bash call).
  for (const secret of findSecrets(command)) blockers.push(`command text: likely ${secret}`);

  const candidates = new Map(); // file -> read from working tree?
  for (const file of staged) candidates.set(file, stageAll);
  for (const file of chained) if (!candidates.has(file)) candidates.set(file, true);

  for (const [file, fromWorktree] of candidates) {
    if (ENV_FILE.test(file) && !ENV_TEMPLATE.test(file)) {
      blockers.push(`${file}: .env file is being committed (keep secrets out of git; commit a .env.example instead)`);
      continue;
    }
    if (LOCKFILES.test(file)) continue;

    const content = fromWorktree
      ? (() => { try { return fs.readFileSync(path.join(cwd, file), 'utf8'); } catch { return null; } })()
      : git(cwd, ['show', `:${file}`]);
    if (content === null || content.length > MAX_FILE_BYTES || content.includes('\0')) continue;

    for (const secret of findSecrets(content)) blockers.push(`${file}: likely ${secret}`);
    if (JS_TS.test(file)) {
      lintable.push(file);
      for (const issue of findCodeIssues(content)) warnings.push(`${file}: ${issue}`);
    }
  }

  const lint = runEslint(cwd, lintable);
  if (lint) warnings.push(`ESLint reported errors:\n${lint}`);
  for (const problem of validateCommitMessage(command)) warnings.push(problem);

  if (blockers.length > 0) {
    block('BLOCKED: this commit appears to contain secrets. Remove them (use environment variables or a secrets manager), ' +
      'rotate anything that was real, and unstage .env files.\n  - ' + blockers.join('\n  - ') +
      (warnings.length ? '\nAlso noticed:\n  - ' + warnings.join('\n  - ') : ''));
  }
  if (warnings.length > 0) {
    context('Commit quality warnings (the commit is allowed, fix them if reasonable):\n  - ' + warnings.join('\n  - '));
  }
});
